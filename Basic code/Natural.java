//WAP to print sum of first 10 natural number

class Natural {
    public static void main(String[] args) 
    {
      int i, Sum=0; 
      for(i=1;i<=10;i++)
    {
      Sum=Sum+i;
      System.out.println(Sum);
   }
   System.out.println("The sum of first 10 natural is"+Sum);
}
}
       
     

